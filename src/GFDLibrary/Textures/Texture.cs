        public override ResourceType ResourceType => ResourceType.Texture;

        public string Name { get; set; }

        public TextureFormat Format { get; set; }

        public byte[] Data { get; set; }

        // 1C
        [FormerName( "Field1C" )]
        public byte MinificationFilter { get; set; }

        // 1D
        [FormerName( "Field1D" )]
        public byte MagnificationFilter { get; set; }

        // 1E
        [FormerName( "Field1E" )]
        public byte WrapModeU { get; set; }

        // 1F
        [FormerName( "Field1F" )]
        public byte WrapModeV { get; set; }

        public bool IsDefaultTexture { get; private set; }
        public bool IsTexSourceExternal { get; set; } = false;

        public Texture()
        {          
        }

        public Texture( uint version ) : base( version )
        {
        }

        public Texture( string name, TextureFormat format, byte[] data ) : this()
        {
            Name = name;
            Format = format;
            Data = data;
            MinificationFilter = 1;
            MagnificationFilter = 1;
            WrapModeU = 0;
            WrapModeV = 0;
        }

        public Texture( string name, TextureFormat format, byte[] data, byte minificationFilter, byte magnificationFilter, byte wrapModeU, byte wrapModeV ) : this()
        {
            Name = name;
            Format = format;
            Data = data;
            MinificationFilter = minificationFilter;
            MagnificationFilter = magnificationFilter;
            WrapModeU = wrapModeU;
            WrapModeV = wrapModeV;
        }

        public static Texture CreateDefaultTexture(string name)
        {
            return new Texture( name, TextureFormat.DDS, sDummyTextureData ) { IsDefaultTexture = true };
        }
        public static Texture CreateDefaultTextureMetaphor( string name )
        {
            return new Texture( name, TextureFormat.DDS, sDummyTextureDataMetaphor ) { IsDefaultTexture = true };
        }

        protected override void ReadCore( ResourceReader reader )
        {
            Name = reader.ReadString();
            Format = ( TextureFormat )reader.ReadInt16();
            if ( !Enum.IsDefined( typeof( TextureFormat ), Format ) )
                throw new InvalidDataException( $"Unknown texture format: {(int)Format}" );
            int size = reader.ReadInt32();
            Data = reader.ReadBytes( reader.ValidateCount( size ) );
            MinificationFilter = reader.ReadByte();
            MagnificationFilter = reader.ReadByte();
            WrapModeU = reader.ReadByte();
            WrapModeV = reader.ReadByte();
        }

        protected override void WriteCore( ResourceWriter writer )
        {
            writer.WriteString( Name );
            writer.WriteInt16( ( short ) Format );
            if (IsTexSourceExternal)
            {
                writer.WriteInt32( sDummyTextureDataMetaphor.Length );
                writer.WriteBytes( sDummyTextureDataMetaphor );
            } else
            {
                writer.WriteInt32( Data.Length );
                writer.WriteBytes( Data );
            }
            writer.WriteByte( MinificationFilter );
            writer.WriteByte( MagnificationFilter );
            writer.WriteByte( WrapModeU );
            writer.WriteByte( WrapModeV );
        }

        public override string ToString() => Name;
